import queue, time
from vools.vconcurrent.bridges import (PipePair, ChannelBridge, QueueBridge, EventBridge,
    StreamBridge, bridge_queues, ThreadProcessBridge)
fails = []
def check(label, got, expect):
    ok = got == expect
    print(f"{label}: {got!r} {'OK' if ok else '⚠ EXPECT '+repr(expect)}")
    if not ok: fails.append(label)
def tryit(label, fn):
    try: print(f"{label}: {fn()!r}")
    except Exception as e: print(f"{label}: {type(e).__name__}: {str(e)[:65]}")

print("=== PipePair ===")
pp = PipePair()
tryit("send a->b", lambda: (pp.a.send('hi'), pp.b.recv())[1])
tryit("send b->a", lambda: (pp.b.send('yo'), pp.a.recv())[1])
pp.close()
print()
print("=== ChannelBridge ===")
cb = ChannelBridge()
tryit("send", lambda: cb.send('msg'))
tryit("poll", lambda: cb.poll())
tryit("recv", lambda: cb.recv())
tryit("send_json", lambda: cb.send_json({'a': 1}))
tryit("recv_json", lambda: cb.recv_json())
tryit("send_pickle", lambda: cb.send_pickle({'b': 2}))
tryit("recv_pickle", lambda: cb.recv_pickle())
tryit("closed 属性", lambda: cb.closed)
cb.close()
tryit("closed 后 closed", lambda: cb.closed)
print()
print("=== QueueBridge ===")
src, dst = queue.Queue(), queue.Queue()
src.put(1); src.put(2)
qb = QueueBridge(src, dst)
qb.start(); time.sleep(0.2); qb.stop()
print("QueueBridge 传输结果:", dst.qsize(), "| is_running:", qb.is_running())
print()
print("=== EventBridge ===")
eb = EventBridge()
tryit("is_set", lambda: eb.is_set())
tryit("set 后", lambda: (eb.set(), eb.is_set())[1])
tryit("wait(0.05)", lambda: eb.wait(0.05))
tryit("clear 后", lambda: (eb.clear(), eb.is_set())[1])
print()
print("=== StreamBridge ===")
sb = StreamBridge()
tryit("send/recv", lambda: (sb.send('x'), sb.recv())[1])
tryit("qsize", lambda: sb.qsize())
sb.close()
print()
print("=== bridge_queues ===")
q1, q2 = queue.Queue(), queue.Queue()
r = bridge_queues(q1, q2)
print("bridge_queues 返回:", type(r).__name__, len(r))
q1.put('a'); time.sleep(0.15)
print("q2 收到:", q2.qsize())
print()
print("fails:", fails)
