# 函数调用
# ============================================================================

def _call_ts_function(js_file: Path, args: List[Any]) -> Any:
    """通过 Node.js 子进程执行 JS 并返回结果"""
    node = shutil.which('node')
    if not node:
        raise RuntimeError('Node.js 不可用，无法执行 TypeScript 桥接')

    payload = json.dumps({'args': args}, ensure_ascii=False)

    try:
        result = subprocess.run(
            [node, str(js_file)],
            input=payload,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            text=True,
            timeout=30,
        )

        output = result.stdout.strip()
        if not output:
            raise RuntimeError(f'Node.js 无输出: stderr={result.stderr}')

        data = json.loads(output)
        if not data.get('ok'):
            raise RuntimeError(f'TS 执行失败: {data.get("error")}\n{data.get("stack", "")}')

        return data.get('result')
    except subprocess.TimeoutExpired:
        raise RuntimeError('TS 执行超时（>30s）')
    except json.JSONDecodeError as e:
        raise RuntimeError(f'TS 输出无法解析为 JSON: {e}\n输出: {output[:500]}')


