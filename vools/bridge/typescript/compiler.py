def compile_and_run(source: str, func_name: str, param_names: List[str], args: List[Any]) -> Any:
    """便捷入口：直接编译运行"""
    src = _generate_ts_source(source, func_name, param_names)
    cache_key = hashlib.md5(src.encode()).hexdigest()[:16]
    js_file = _compile_ts_code(src, cache_key)
    return _call_ts_function(js_file, args)


