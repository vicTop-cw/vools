class TypeScriptBridge(LangBridge):
    """TypeScript/JavaScript 语言桥接实现。

    通过 Node.js 子进程执行编译后的 JS 代码，使用 JSON 序列化进行数据交换。
    支持 TypeScript 和纯 JavaScript。

    Attributes:
        name: 语言名称 'typescript'。
        file_ext: 源文件扩展名 '.ts'。
        lib_ext: 编译产物扩展名 '.js'。
        _executor: 异步执行线程池。
    """

    name = 'typescript'
    is_compiled = False
    lang_type = LangType.INTERPRETED
    file_ext = '.ts'
    lib_ext = '.js'

    def __init__(self):
        """初始化 TypeScriptBridge 实例。"""
        super().__init__()
        self._executor = ThreadPoolExecutor(
            max_workers=4, thread_name_prefix='ts-bridge'
        )

    def default_cache_dir(self) -> str:
        """默认缓存目录路径。

        Returns:
            str: 默认缓存目录的绝对路径。
        """
        return str(_TS_CACHE_DIR)

    def compiler_available(self) -> bool:
        """检查 TypeScript 运行环境是否可用（需要 Node.js）。

        Returns:
            bool: Node.js 可用时返回 True，否则返回 False。
        """
        return ts_compiler_available()

    def _execute_code(self, package_path, func_name, args, ret_type=None):
        """解包并执行代码。"""
        import zipfile, tempfile, os, shutil
        from pathlib import Path

        tmpdir = tempfile.mkdtemp()
        try:
            with zipfile.ZipFile(package_path, 'r') as zf:
                zf.extractall(tmpdir)

            source_file = os.path.join(tmpdir, self.get_source_filename(func_name))
            source = Path(source_file).read_text(encoding='utf-8')

            # Compile TS to JS and write to temp file
            js_content = _strip_typescript(source)
            js_file = os.path.join(tmpdir, 'main.js')
            Path(js_file).write_text(js_content, encoding='utf-8')

            # Execute via stdin/stdout protocol
            return _call_ts_function(Path(js_file), list(args))
        finally:
            shutil.rmtree(tmpdir, ignore_errors=True)

    def generate_code(self, spec: FunctionSpec) -> str:
        """根据函数规格生成 TypeScript 源码。

        支持两种函数体提取方式：
        1. 优先使用 spec.body（return 字符串方式，与其他语言一致）
        2. fallback 到函数的 __doc__（旧版兼容方式）

        Args:
            spec: 函数规格对象，包含函数名、参数、函数体等信息。

        Returns:
            str: 生成的完整 TypeScript 源码（含入口模板）。
        """
        parts = []

        # 1. module_code（放在最前面，用于 import 语句、类型定义等）
        if spec.module_code:
            parts.append(spec.module_code)

        # 2. 依赖函数（递归生成每个依赖函数的 TypeScript 代码）
        for dep in spec.dependencies:
            dep_code = self.generate_code(dep)
            parts.append(dep_code)

        # 3. 主函数
        user_code = spec.body or ''
        func_name = spec.name
        param_names = list(spec.annotations.keys()) if spec.annotations else []
        if 'return' in param_names:
            param_names.remove('return')
        parts.append(_generate_ts_source(user_code, func_name, param_names))

        return '\n\n'.join(parts)

    def compile_code(self, code: str, func_name: str, cache_dir: Optional[str] = None) -> str:
        """编译 TypeScript 代码为 JavaScript 文件。

        Args:
            code: TypeScript 源代码字符串。
            func_name: 函数名称（用于缓存标识）。
            cache_dir: 自定义缓存目录，为 None 时使用默认目录。

        Returns:
            str: 编译后的 JS 文件路径。
        """
        cache_key = hashlib.md5(code.encode()).hexdigest()[:16]
        if cache_dir:
            cache_subdir = Path(cache_dir) / cache_key
            cache_subdir.mkdir(parents=True, exist_ok=True)
            ts_file = cache_subdir / 'main.ts'
            js_file = cache_subdir / 'main.js'
            ts_file.write_text(code, encoding='utf-8')
            js_content = _strip_typescript(code)
            js_file.write_text(js_content, encoding='utf-8')
            return str(js_file)
        js_file = _compile_ts_code(code, cache_key)
        return str(js_file)

    def call_func(self, lib_path: str, func_name: str, args: tuple, ret_type: Optional[type] = None) -> Any:
        """调用编译后的 JavaScript 函数。

        Args:
            lib_path: JS 文件路径。
            func_name: 函数名称（当前未使用，入口已固化在模板中）。
            args: 函数参数元组。
            ret_type: 返回值类型（当前未使用，由 JSON 反序列化自动推断）。

        Returns:
            Any: 函数执行结果，已从 JSON 反序列化为 Python 对象。

        Raises:
            RuntimeError: Node.js 不可用或执行失败时抛出。
        """
        return _call_ts_function(Path(lib_path), list(args))

    def _get_project_hash(self, project_dir: str) -> str:
        """计算项目所有源文件的内容哈希。

        TypeScript 支持 .ts 和 .js 两种源文件扩展名。

        Args:
            project_dir: 项目根目录路径。

        Returns:
            str: 项目源文件内容的 MD5 哈希值。
        """
        import os
        import hashlib

        hasher = hashlib.md5()
        if not os.path.isdir(project_dir):
            return hasher.hexdigest()

        src_files = []
        for root, dirs, files in os.walk(project_dir):
            for f in files:
                if f.endswith('.ts') or f.endswith('.js'):
                    src_files.append(os.path.join(root, f))

        src_files.sort()

        for filepath in src_files:
            try:
                with open(filepath, 'rb') as f:
                    hasher.update(f.read())
            except Exception:
                pass

        return hasher.hexdigest()

    def compile_project(self, project_dir: str, entry: str, output_dir: Optional[str] = None) -> str:
        """编译整个 TypeScript 项目。

        扫描项目目录下所有 .ts 和 .js 文件，打包成一个可执行的 JS 文件。
        如果 entry 为 'main'，生成包含 CLI 入口的完整脚本；
        否则生成导出入口函数的模块文件。

        Args:
            project_dir: 项目目录路径。
            entry: 入口函数名，'main' 表示生成可执行脚本。
            output_dir: 输出目录，为 None 时使用缓存目录。

        Returns:
            str: 输出 JS 文件的路径。
        """
        project_path = Path(project_dir)
        files = []
        for ext in ('*.ts', '*.js'):
            files.extend(sorted(project_path.rglob(ext)))

        if not files:
            raise FileNotFoundError(f"在 {project_dir} 中未找到 .ts 或 .js 文件")

        code_hash = self._get_project_hash(project_dir)
        out_dir = Path(output_dir) if output_dir else _TS_CACHE_DIR / f'proj_{code_hash[:16]}'
        out_dir.mkdir(parents=True, exist_ok=True)

        out_file = out_dir / 'index.js'

        if out_file.exists():
            return str(out_file)

        parts = []
        parts.append('// Auto-generated by vools.bridge.typescript')
        parts.append(f'// Project: {project_dir}')
        parts.append('')

        for f in files:
            rel_path = f.relative_to(project_path)
            parts.append(f'// ---- {rel_path} ----')
            content = f.read_text(encoding='utf-8')
            if f.suffix == '.ts':
                content = _strip_typescript(content)
            parts.append(content)
            parts.append('')

        if entry == 'main':
            parts.append('// CLI entry point')
            parts.append("if (require.main === module) {")
            parts.append("    let input = '';")
            parts.append("    process.stdin.setEncoding('utf-8');")
            parts.append("    process.stdin.on('data', (chunk) => { input += chunk; });")
            parts.append("    process.stdin.on('end', async () => {")
            parts.append("        let okFlag = true;")
            parts.append("        let resultValue = null;")
            parts.append("        let errMsg = '';")
            parts.append("        try {")
            parts.append("            const data = JSON.parse(input);")
            parts.append("            const args = data.args || [];")
            parts.append("            if (typeof main === 'function') {")
            parts.append("                resultValue = await main(...args);")
            parts.append("            } else {")
            parts.append("                resultValue = null;")
            parts.append("            }")
            parts.append("        } catch (err) {")
            parts.append("            okFlag = false;")
            parts.append("            errMsg = err && err.message ? err.message : String(err);")
            parts.append("        }")
            parts.append("        const outPayload = { ok: okFlag, result: resultValue, error: errMsg };")
            parts.append("        process.stdout.write(JSON.stringify(outPayload));")
            parts.append("    });")
            parts.append("}")
        else:
            parts.append(f'// Entry: {entry}')
            parts.append(f'module.exports = {{ {entry} }};')

        out_file.write_text('\n'.join(parts), encoding='utf-8')
        return str(out_file)


