TS_FUNCTION_TEMPLATE = '''// Auto-generated by vools.bridge.typescript
// Source hash: {hash}

function {func_name}({param_list}) {{
    {user_code}
}}

// Main entry point
async function __vools_main(args) {{
    const params = {param_names};
    const userFn = {func_name};

    // Call with positional args
    if (params.length === 0) {{
        return await userFn();
    }} else if (params.length === 1) {{
        return await userFn(args[0]);
    }} else {{
        return await userFn.apply(null, args);
    }}
}}

// CLI entry
if (require.main === module) {{
    let input = '';
    process.stdin.setEncoding('utf-8');
    process.stdin.on('data', (chunk) => {{ input += chunk; }});
    process.stdin.on('end', async () => {{
        let okFlag = true;
        let resultValue = null;
        let errMsg = '';
        let errStack = '';
        try {{
            const data = JSON.parse(input);
            const args = data.args || [];
            resultValue = await __vools_main(args);
        }} catch (err) {{
            okFlag = false;
            errMsg = err && err.message ? err.message : String(err);
            errStack = err && err.stack ? err.stack : '';
        }}
        const outPayload = {{ ok: okFlag, result: resultValue, error: errMsg, stack: errStack }};
        process.stdout.write(JSON.stringify(outPayload));
    }});
}}
'''


def _generate_ts_source(user_code: str, func_name: str, param_names: List[str]) -> str:
    """生成 TypeScript 源码"""
    code_hash = hashlib.md5(user_code.encode()).hexdigest()[:12]
    return TS_FUNCTION_TEMPLATE.format(
        hash=code_hash,
        user_code=user_code,
        func_name=func_name,
        param_list=', '.join(param_names),
        param_names=json.dumps(param_names),
    )


