def _compile_ts_code(source: str, cache_key: str) -> Path:
    """
    编译 TypeScript 源码为 JavaScript
    返回 JS 文件路径

    注意：直接输出 JS，不使用 tsc。
    TypeScript 类型注解由 _strip_typescript() 去除。
    这种方式更简单可靠，避免 tsc 5+ 的简写优化破坏对象字面量。
    """
    cache_subdir = _TS_CACHE_DIR / cache_key
    cache_subdir.mkdir(parents=True, exist_ok=True)

    ts_file = cache_subdir / 'main.ts'
    js_file = cache_subdir / 'main.js'

    ts_file.write_text(source, encoding='utf-8')

    # 直接将 TS 转为 JS（去除类型注解）
    js_content = _strip_typescript(source)
    js_file.write_text(js_content, encoding='utf-8')

    return js_file


def _strip_typescript(source: str) -> str:
    """简单去除 TypeScript 类型注解（作为 tsc 不可用时的回退）"""
    import re
    lines = source.split('\n')
    out_lines = []
    for line in lines:
        # 跳过 TS 特定的语法
        stripped = line
        # interface / type alias / declare 整行删除
        if re.match(r'^\s*(interface|type\s+\w+\s*=)\s', stripped):
            continue
        # 函数返回类型: function fn(): number { -> function fn() {
        stripped = re.sub(r'\)\s*:\s*[A-Za-z_<>|][\w<>|,\s\[\]\?]*\s*(\{)', r') \1', stripped)
        # 函数返回类型(箭头函数): const fn = (): number =>  -> const fn = () =>
        stripped = re.sub(r'\)\s*:\s*[A-Za-z_<>|][\w<>|,\s\[\]\?]*\s*(=>)', r') \1', stripped)
        # 函数参数类型(箭头函数): (x: number, y: string) =>  -> (x, y) =>
        # 注意：要避开对象字面量的 key: value 形式
        if '=>' in stripped and not re.search(r'^\s*[a-zA-Z_]+\s*:', stripped):
            stripped = re.sub(r':\s*[A-Za-z_<>|][\w<>|,\s\[\]\?]*?(?=[,)])', '', stripped)
        # 变量类型注解: const x: number = 5 -> const x = 5
        # 但不能破坏对象字面量 {key: value}
        stripped = re.sub(r'(?<=[\s,;\(])\b([a-zA-Z_]\w*)\s*:\s*[A-Za-z_<>|][\w<>|,\s\[\]\?]*\s*(?==)', r'\1', stripped)
        # 参数类型: function add(a: int, b: int) -> function add(a, b)
        # 只在函数定义上下文中
        if re.search(r'\bfunction\s+\w+\s*\(', stripped) or re.search(r'\b\w+\s*=\s*\(', stripped):
            stripped = re.sub(r':\s*[A-Za-z_<>|][\w<>|,\s\[\]\?]*?(?=[,)])', '', stripped)
        out_lines.append(stripped)
    return '\n'.join(out_lines)


