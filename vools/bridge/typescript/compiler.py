def is_node_available() -> bool:
    """检测 node 是否可用"""
    return shutil.which('node') is not None


def is_typescript_available() -> bool:
    """检测 tsc 是否可用"""
    return shutil.which('tsc') is not None or shutil.which('npx') is not None


