class TSFuture:
    """TypeScript 异步执行 Future"""

    def __init__(self, executor: ThreadPoolExecutor, js_file: Path, args: List[Any]):
        self._executor = executor
        self._js_file = js_file
        self._args = args
        self._future: Future = executor.submit(_call_ts_function, js_file, args)

    def result(self, timeout: Optional[float] = None) -> Any:
        return self._future.result(timeout=timeout)

    def __await__(self):
        # 用线程池包装实现 await
        import asyncio
        loop = asyncio.get_event_loop()
        return loop.run_in_executor(None, self._future.result).__await__()


