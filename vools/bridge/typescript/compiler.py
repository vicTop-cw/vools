PY_TO_TS_TYPE = {
    int: 'number',
    float: 'number',
    str: 'string',
    bool: 'boolean',
    list: 'any[]',
    dict: 'Record<string, any>',
    type(None): 'null',
}

TS_TO_PY_TYPE = {
    'number': (int, float),
    'string': str,
    'boolean': bool,
    'any[]': list,
    'Record<string, any>': dict,
    'null': type(None),
}


def get_ts_type(py_type: type) -> str:
    """Python 类型 -> TypeScript 类型"""
    return PY_TO_TS_TYPE.get(py_type, 'any')


