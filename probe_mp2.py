from vools.vconcurrent.multiprocessing_mod import SharedValue, SharedDict, SharedList, PipeChannel
fails = []
def check(label, got, expect):
    ok = got == expect
    print(f"{label}: {got!r} {'OK' if ok else '⚠ EXPECT '+repr(expect)}")
    if not ok: fails.append(label)
def tryit(label, fn):
    try: print(f"{label}: {fn()!r}")
    except Exception as e: print(f"{label}: {type(e).__name__}: {str(e)[:65]}")

print("=== SharedValue ===")
v = SharedValue('i', 5)
check("get", v.get(), 5)
v.set(9); check("set/get", v.get(), 9)
tryit("错误类型写入", lambda: v.set('str'))
tryit("非法 typecode", lambda: SharedValue('zz'))
print()
print("=== SharedDict ===")
d = SharedDict({'a': 1})
check("get", d.get('a'), 1)
d.update({'b': 2}); check("update", d.to_dict(), {'a':1,'b':2})
check("keys", sorted(d.keys()), ['a','b'])
check("items", d.items(), [('a',1),('b',2)])
check("values", d.values(), [1,2])
d.close()
tryit("close 后 get", lambda: d.get('a'))
print()
print("=== SharedList ===")
l = SharedList([1,2])
l.append(3); check("append", l.to_list(), [1,2,3])
l.extend([4,5]); check("extend", l.to_list(), [1,2,3,4,5])
check("pop", l.pop(), 5)
check("pop 后", l.to_list(), [1,2,3,4])
l.close()
tryit("close 后 append", lambda: l.append(9))
print()
print("=== PipeChannel ===")
pc = PipeChannel()
tryit("parent send / child recv", lambda: (pc.parent_conn.send('p2c'), pc.child_conn.recv())[1])
tryit("child send / parent recv", lambda: (pc.child_conn.send('c2p'), pc.parent_conn.recv())[1])
tryit("bytes 通道", lambda: (pc.parent_conn.send_bytes(b'raw'), pc.child_conn.recv_bytes())[1])
pc.close()
print()
print("fails:", fails)
