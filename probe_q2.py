from vools.vconcurrent.queues import VQueue, VPriorityQueue, VLifoQueue, BoundedChannel
fails = []
def case(label, fn, expect=None):
    try:
        r = fn()
        ok = (expect is None) or (r == expect)
        print(f"{label}: {r!r} {'OK' if ok else '⚠ EXPECT '+repr(expect)}")
        if not ok: fails.append(label)
    except Exception as e:
        print(f"{label}: {type(e).__name__}: {str(e)[:65]}"); fails.append(label)

q = VQueue(); q.put(1); q.put(2)
case("get", lambda: q.get(), 1)
case("qsize", lambda: q.qsize(), 1)
case("is_empty", lambda: q.is_empty(), False)
case("peek", lambda: q.peek(), 2)
case("get 后 empty", lambda: (q.get(), q.is_empty())[1], True)
case("get_nowait 空", lambda: q.get_nowait() if hasattr(q,'get_nowait') else q.get_timeout(0))
case("get_timeout(0.05) 空", lambda: q.get_timeout(0.05))
print()
bq = VQueue(maxsize=2); bq.put('a'); bq.put('b')
case("is_full", lambda: bq.is_full(), True)
case("put_timeout 满", lambda: bq.put_timeout('c', 0.05))
print()
pq = VPriorityQueue()
for i in (3,1,2): pq.put(i)
case("优先级出队", lambda: [pq.get() for _ in range(3)], [1,2,3])
lq = VLifoQueue()
for i in (1,2,3): lq.put(i)
case("LIFO 出队", lambda: [lq.get() for _ in range(3)], [3,2,1])
print()
ch = BoundedChannel(maxsize=1)
case("send", lambda: ch.send('x'))
case("is_full", lambda: ch.is_full(), True)
case("recv", lambda: ch.recv(), 'x')
case("close", lambda: ch.close())
case("closed 标记", lambda: ch.is_closed(), True)
case("close 后 send", lambda: ch.send('y'))
case("close 后 recv", lambda: ch.recv())
print()
print("fails:", fails)
